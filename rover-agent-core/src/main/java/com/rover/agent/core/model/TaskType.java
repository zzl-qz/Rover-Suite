package com.rover.agent.core.model;

/**
 * 任务类型：一次提问最终以什么形态执行，前端据此选择展示方式，而不是靠问题文本猜。
 *
 * 只有两个值，因为当前只有两种真实存在的执行形态：人工提问走 {@link #CONVERSATION}
 * （模型在对话中自主决定调用哪些工具），机器事件走 {@link #INVESTIGATION}
 * （告警触发的有界自动调查）。「查询 / 解释 / 处置」不是独立的执行链，而是对话里
 * 模型自己查什么、怎么答的结果——按问题预先归类正是已经废掉的旧做法。
 *
 * 将来真正的处置能力上线时再新增 {@code ACTION}，而不是提前放一个现在不存在的形态。
 */
public enum TaskType {

    /**
     * 智能问答：模型自主判断要不要取数、取哪几项，并直接作答。
     *
     * 它是人工会话的唯一形态，也是一次提问最诚实的形态：同一个入口既可能什么都不查（问候、闲聊），
     * 也可能连查五六项（跨源排障），还可能一句话里既有闲聊也有取数。
     */
    CONVERSATION,

    /** 自动调查：告警 / 机器事件触发的有界只读调查，轮数与调用次数由代码强制封顶。 */
    INVESTIGATION
}
