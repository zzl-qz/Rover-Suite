package com.rover.agent.core.model;

/** 任务执行形态：人工对话或机器事件调查。 */
public enum TaskType {

    /**
     * 智能问答：模型自主判断要不要取数、取哪几项，并直接作答。
     *
     * 它是人工会话的唯一形态，也是一次提问最诚实的形态：同一个入口既可能什么都不查（问候、闲聊），
     * 也可能连查五六项（跨源排障），还可能一句话里既有闲聊也有取数。
     */
    CONVERSATION,

    /** 自动调查：告警 / 机器事件触发的有界只读调查，轮数与调用次数由代码强制封顶。 */
    INVESTIGATION
}
