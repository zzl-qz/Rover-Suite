package com.rover.agent.core.model;

/**
 * 处置计划的风险等级：给人工判断「这个建议值不值得采纳」用的粗粒度分级。
 *
 * 分级依据是「一旦执行，对可用容量的影响有多大」，不是对动作本身的道德评价：
 * 恢复实例通常只会增加容量（LOW）；摘除实例会降低容量（MEDIUM / HIGH）；
 * 调整超时与限流会改变请求行为，一律视为 MEDIUM。
 */
public enum RiskLevel {

    /** 低风险：执行后不影响可用容量 */
    LOW,

    /** 中风险：执行后可用容量或请求行为会变化，需要人工确认 */
    MEDIUM,

    /** 高风险：执行后可能造成容量显著下降或请求行为剧烈变化 */
    HIGH
}