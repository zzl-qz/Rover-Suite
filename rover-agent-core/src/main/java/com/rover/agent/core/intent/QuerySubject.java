package com.rover.agent.core.intent;

/**
 * 状态查询问的是哪一类事实：供查询执行侧选择只读能力，避免各处重复维护关键词。
 */
public enum QuerySubject {

    /** 问实例：数量、健康、注册情况 */
    INSTANCE,

    /** 问流量：QPS、请求量、错误率、拒绝计数 */
    METRIC,

    /** 问路由：指向哪个服务、前缀与匹配情况 */
    ROUTE,

    /** 问配置：限流、熔断、超时、采样率等当前生效值 */
    CONFIG,

    /** 问事件：注册、注销、剔除、标记不健康等注册中心的变更经过 */
    EVENT,

    /** 问哪一类事实都不明显：由执行侧按目标是否确定来选 */
    NONE
}