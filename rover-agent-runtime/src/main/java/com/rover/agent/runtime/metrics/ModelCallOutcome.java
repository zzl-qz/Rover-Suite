package com.rover.agent.runtime.metrics;

import java.util.Locale;

/**
 * 一次模型调用的结局：把「没成功」拆成可数的几种原因。
 *
 * <p>为什么需要它：模型是可选能力，失败是常态而不是异常。只记「失败了几次」回答不了
 * 「命中率为什么掉」——是没配模型（部署问题）、等超时了（网络/容量问题）、调用报错（凭证/参数问题）、
 * 还是模型答了但输出不合契约（提示词问题），这四种的处置完全不同。用有限枚举把它们分开后，
 * 指标可以直接给出分布，日志也只需在真正异常的分支上发声。
 *
 * <p>取值是有限枚举，因此可以安全地作为指标标签；{@link #OK} 之外的取值都表示本次没拿到可用判断，
 * 调用方按各自约定回退到确定性路径。
 */
public enum ModelCallOutcome {

    /** 拿到非空响应，且调用方判定可用。 */
    OK,
    /** 未配置模型：不问不打（本地开发与纯规则部署的常态）。 */
    NOT_CONFIGURED,
    /** 配置了但客户端没建起来（如缺少密钥、地址非法）。 */
    UNAVAILABLE,
    /** 超过本场景的等待上限（含重试一次后仍未返回）。 */
    TIMEOUT,
    /** 调用抛出非超时异常（鉴权失败、模型不存在、参数错误等）。 */
    ERROR,
    /** 调用成功但没有内容。 */
    EMPTY,
    /** 有内容但不符合输出契约（越界取值、缺必需字段），已整条丢弃。 */
    REJECTED;

    /** 是否拿到了可用结果；只有 {@link #OK} 为真。 */
    public boolean ok() {
        return this == OK;
    }

    /** 指标标签取值：小写，与 model 标签的规范化风格一致。 */
    public String tag() {
        return name().toLowerCase(Locale.ROOT);
    }
}
